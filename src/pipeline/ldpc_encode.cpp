#include "ldpc_encode.h"
#include "ldpc_code.h"
#include "HRA_56_56.h"

std::array<uint8_t, 112> ldpc_encode(const std::array<uint8_t, 56>& s)
{
    static const LDPCCode<56, 56> code(HRA_56_56);
    return code.encode(s);
}
