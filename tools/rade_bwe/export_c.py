#!/usr/bin/env python3
"""Exports a trained predictor as C for Opus's nnet code (as used by RADE),
plus a header of reference input/output frames for a unit test.

The input normalization is folded into the convolution, and the 2-layer GRU
is written as two single-layer GRUs, so that the C side is just
compute_generic_conv1d, compute_generic_gru twice and compute_generic_dense.

Usage: export_c.py <model.pt> <outdir> <test prefix> [frames]

Opus's weight-exchange package (opus/dnn/torch/weight-exchange) needs to be on
PYTHONPATH.
"""
import os
import sys

import numpy as np
import torch
from torch import nn

from wexchange.c_export import CWriter
from wexchange.torch import dump_torch_conv1d_weights, dump_torch_dense_weights, dump_torch_gru_weights

import bwe

model_path, outdir, test_prefix = sys.argv[1:4]
n_frames = int(sys.argv[4]) if len(sys.argv) > 4 else 400

ck = torch.load(model_path, map_location="cpu")
a = ck["args"]
assert a["lookahead"] == 0, "the C version is causal only"
model = bwe.Predictor(a["hidden"], a["layers"])
model.load_state_dict(ck["state"])
model.eval()

# Fold (x - mean) / std into the convolution.
conv = nn.Conv1d(bwe.N_IN, a["hidden"], 3)
with torch.no_grad():
    w = model.conv.weight / model.std[None, :, None]
    conv.weight.copy_(w)
    conv.bias.copy_(model.conv.bias - (w * model.mean[None, :, None]).sum(dim=(1, 2)))

grus = []
for layer in range(a["layers"]):
    g = nn.GRU(a["hidden"], a["hidden"], 1, batch_first=True)
    with torch.no_grad():
        for p in ["weight_ih", "weight_hh", "bias_ih", "bias_hh"]:
            getattr(g, p + "_l0").copy_(getattr(model.gru, "%s_l%d" % (p, layer)))
    grus.append(g)

os.makedirs(outdir, exist_ok=True)
msg = "Auto-generated by export_c.py from %s; do not edit." % os.path.basename(model_path)
writer = CWriter(os.path.join(outdir, "rade_bwe_data"), message=msg, model_struct_name="RadeBwe", add_typedef=True)
dump_torch_conv1d_weights(writer, conv, "bwe_conv", quantize=False)
for i, g in enumerate(grus):
    dump_torch_gru_weights(writer, g, "bwe_gru%d" % (i + 1), quantize=False)
dump_torch_dense_weights(writer, model.out, "bwe_out", quantize=False)
writer.header.write("\n#define BWE_NB_GRUS %d\n" % len(grus))
writer.close()

# Reference frames: the start of the first test utterances, with the model run
# from its initial state as the C code will be.
wb, nb, idx = bwe.load_pairs(test_prefix)
start, end = idx[0], min(idx[1], idx[0] + n_frames)
x = nb[start:end]
y = bwe.apply(model, x)

# Check the folded/split version gives the same as the original.
with torch.no_grad():
    t = torch.as_tensor(x[None, :, :bwe.N_IN]).transpose(1, 2)
    t = torch.cat([t[..., :1], t[..., :1], t], dim=2)
    h = torch.tanh(conv(t)).transpose(1, 2)
    for g in grus:
        h, _ = g(h)
    o = model.out(h)[0].numpy()
z = np.concatenate([x[:, :bwe.NB_BANDS] + o[:, :bwe.NB_BANDS], x[:, bwe.PITCH:bwe.PITCH + 1], x[:, bwe.CORR:bwe.CORR + 1] + o[:, bwe.NB_BANDS:]], axis=1)
err = np.abs(z - y[:, :bwe.N_IN]).max()
print("folded model max difference: %.3g" % err)
assert err < 1e-4


def c_array(f, name, a):
    f.write("static const float %s[%d][%d] = {\n" % (name, a.shape[0], a.shape[1]))
    for row in a:
        f.write("    {" + ", ".join("%.9gf" % v for v in row) + "},\n")
    f.write("};\n\n")


with open(os.path.join(outdir, "rade_bwe_test_vectors.h"), "w") as f:
    f.write("/* %s */\n\n" % msg.replace("from", "with reference frames from"))
    f.write("#define BWE_TEST_FRAMES %d\n#define BWE_TEST_FEATURES %d\n\n" % (len(x), bwe.N_IN))
    c_array(f, "bwe_test_input", x[:, :bwe.N_IN])
    c_array(f, "bwe_test_output", y[:, :bwe.N_IN])
print("wrote %s: %d reference frames" % (outdir, len(x)))
